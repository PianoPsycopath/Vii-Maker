import { zipSync, strToU8 } from 'fflate';
import { generateBedrockFiles } from './exporter.js';

const NOSE_GEO_PREFIX = 'geometry.villager_nose_';
const PACK_FOLDER = 'Vii-Maker_RP';
const PACK_VERSION = [1, 0, 0];
const MIN_ENGINE_VERSION = [1, 21, 0];
const PACK_HEADER_UUID = 'c1cfa520-1630-451a-b8b9-548ebc504b62';
const PACK_MODULE_UUID = '9d86928a-6dd1-425a-99ea-4c76a42cb6b7';

const PACK_PATHS = {
  entity: 'entity/villager_v2.entity.json',
  renderControllers: 'render_controllers/villager_v2.render_controllers.json',
  geometry: 'models/entity/villager_v2.geo.json',
  noseGeometry: 'models/entity/villager_nose.geo.json'
};

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47];

export const toFileText = content => (typeof content === 'string' ? content : JSON.stringify(content, null, 2));

const encodeJson = content => strToU8(toFileText(content));

function splitGeometry(GEO) {
  const { format_version = '1.8.0', ...geometries } = GEO;
  const main = {};
  const nose = {};
  for (const [id, definition] of Object.entries(geometries)) {
    (id.startsWith(NOSE_GEO_PREFIX) ? nose : main)[id] = definition;
  }
  const wrap = group => (Object.keys(group).length ? { format_version, ...group } : null);
  return { main: wrap(main), nose: wrap(nose) };
}

/**
 * Generates every JSON file of the pack, keyed by its path inside a resource pack,
 * plus the texture paths (no extension) that the entity definition references.
 */
export function buildBedrockFiles({ manifest, base, over, lookup, lookups, GEO }) {
  const { entityJson, rcJson, stats } = generateBedrockFiles(manifest, base, over, lookup, lookups);
  const geometry = splitGeometry(GEO);

  const json = {
    [PACK_PATHS.entity]: entityJson,
    [PACK_PATHS.renderControllers]: rcJson
  };
  if (geometry.main) json[PACK_PATHS.geometry] = geometry.main;
  if (geometry.nose) json[PACK_PATHS.noseGeometry] = geometry.nose;

  const entityTextures = entityJson['minecraft:client_entity'].description.textures;
  return { json, texturePaths: [...new Set(Object.values(entityTextures))], stats };
}

async function fetchTexture(baseUrl, path, fetchImpl) {
  for (const extension of ['png', 'tga']) {
    try {
      const response = await fetchImpl(`${baseUrl}${path}.${extension}`);
      if (!response.ok) continue;
      const bytes = new Uint8Array(await response.arrayBuffer());
      // The dev server answers unknown URLs with index.html, so check what actually came back.
      const isPng = PNG_SIGNATURE.every((byte, i) => bytes[i] === byte);
      const isHtml = (response.headers.get('content-type') || '').includes('text/html');
      if (extension === 'png' ? isPng : !isHtml && bytes.length) {
        return { file: `${path}.${extension}`, bytes };
      }
    } catch {}
  }
  return null;
}

export async function loadTextures(
  texturePaths,
  { baseUrl = import.meta.env.BASE_URL, fetchImpl = fetch } = {}
) {
  const results = await Promise.all(texturePaths.map(path => fetchTexture(baseUrl, path, fetchImpl)));
  const files = {};
  const missing = [];
  results.forEach((result, index) => {
    if (result) files[result.file] = result.bytes;
    else missing.push(texturePaths[index]);
  });
  return { files, missing };
}

export function describeMissingTextures(missing) {
  if (!missing.length) return '';
  const shown = missing.slice(0, 4).join(', ');
  return ` ${missing.length} texture(s) not found: ${shown}${missing.length > 4 ? ', …' : ''}.`;
}

export function buildAddonManifest() {
  return {
    format_version: 2,
    header: {
      name: 'Vii-Maker Villagers',
      description: 'Custom villager looks generated by Vii-Maker.',
      uuid: PACK_HEADER_UUID,
      version: PACK_VERSION,
      min_engine_version: MIN_ENGINE_VERSION
    },
    modules: [
      {
        type: 'resources',
        description: 'Villager entity, render controllers, geometry and textures.',
        uuid: PACK_MODULE_UUID,
        version: PACK_VERSION
      }
    ]
  };
}

const encodeJsonFiles = json =>
  Object.fromEntries(Object.entries(json).map(([path, content]) => [path, encodeJson(content)]));

export function zipSimple(json) {
  return zipSync(
    Object.fromEntries(Object.entries(json).map(([path, content]) => [path.split('/').pop(), encodeJson(content)]))
  );
}

export function zipAddon(json, textureFiles) {
  const packFiles = {
    'manifest.json': encodeJson(buildAddonManifest()),
    ...encodeJsonFiles(json),
    ...textureFiles
  };
  return zipSync(
    Object.fromEntries(Object.entries(packFiles).map(([path, data]) => [`${PACK_FOLDER}/${path}`, data]))
  );
}

export async function pickResourcePackRoot() {
  const root = await window.showDirectoryPicker({ id: 'villager-maker-pack', mode: 'readwrite' });

  let manifest;
  try {
    const file = await (await root.getFileHandle('manifest.json')).getFile();
    manifest = JSON.parse(await file.text());
  } catch {
    throw new Error('No readable manifest.json in that folder. Pick the pack root, the folder that contains manifest.json.');
  }
  if (!manifest.modules?.some(module => module.type === 'resources')) {
    throw new Error('That manifest is not a resource pack (no "resources" module).');
  }
  return root;
}

async function writePackFile(root, path, data) {
  const parts = path.split('/');
  const fileName = parts.pop();
  let directory = root;
  for (const part of parts) {
    directory = await directory.getDirectoryHandle(part, { create: true });
  }
  const writable = await (await directory.getFileHandle(fileName, { create: true })).createWritable();
  await writable.write(data);
  await writable.close();
}

/** Overwrites the pack's files at their standard paths and never touches the root manifest.json. */
export async function weaveIntoPack(root, json, textureFiles) {
  const entries = [
    ...Object.entries(json).map(([path, content]) => [path, toFileText(content)]),
    ...Object.entries(textureFiles)
  ].filter(([path]) => path.toLowerCase() !== 'manifest.json');

  for (const [path, data] of entries) {
    await writePackFile(root, path, data);
  }
  return entries.length;
}